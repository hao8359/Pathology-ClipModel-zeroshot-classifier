import os
import glob
import json
import torch
import pandas as pd
from PIL import Image
import open_clip
from torch.utils.data import Dataset, DataLoader
from tqdm import tqdm
import wandb

# ==========================================
# 1. Custom JPEG Tiles Dataset
# ==========================================
class WSITileDataset(Dataset):
    def __init__(self, tiles_dir, transform=None):
        self.tiles_dir = tiles_dir
        self.transform = transform
        # Search for all JPEG tiles in the target directory
        self.image_paths = sorted(
            glob.glob(os.path.join(tiles_dir, "*.jpeg")) + 
            glob.glob(os.path.join(tiles_dir, "*.jpg"))
        )
        if len(self.image_paths) == 0:
            raise FileNotFoundError(f"No JPEG tiles found in {tiles_dir}")

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        img_path = self.image_paths[idx]
        image = Image.open(img_path).convert("RGB")
        if self.transform:
            image = self.transform(image)
        return image, os.path.basename(img_path)


def main():
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"Using device: {device}")

    # Set paths for input preprocessed tiles and output predictions
    # Replace this with the actual output directory generated by your preprocessing step
    SLIDE_TILES_DIR = "./WSI-Preprocessing/output/pipeline/de531777-915c-47bc-a3fd-dc59c10b2e54-01Z-00-DX1.FCF4A7E7-A0F9-4B5D-B751-D990703EA261.svs/tiles"
    OUTPUT_CSV = os.path.join(SLIDE_TILES_DIR, "zero_shot_predictions.csv")
    MODEL_PATH = "/home/dechihao/Pathclip-zero-shot-classifier/logs/pathclip_vit_b16_openai_v7_run2/checkpoints/epoch_3.pt"

    # ==========================================
    # 2. Define Classes and Prompts for Liver Pathology
    # ==========================================
    # Adjust class_names and prompt descriptions according to your experimental setup
    label_mapping = {
        "normal": "normal liver tissue",
        "hcc": "liver hepatocellular carcinoma"
    }
    class_names = list(label_mapping.keys())
    text_label_list = [
        f"a histopathology image showing {label_mapping[c]}" 
        for c in class_names
    ]
    print(f"Class labels: {text_label_list}")

    # ==========================================
    # 3. Initialize Weights & Biases (W&B)
    # ==========================================
    wandb.init(
        project="pathclip-zero-shot-classifier", 
        name="pathclip-liver-tiles-eval",
        config={
            "model_path": MODEL_PATH,
            "tiles_dir": SLIDE_TILES_DIR,
            "batch_size": 128,
            "device": device,
            "prompts": text_label_list
        }
    )

    # ==========================================
    # 4. Load PathCLIP Model
    # ==========================================
    model, _, preprocess = open_clip.create_model_and_transforms(
        'ViT-B-16', 
        pretrained=MODEL_PATH,
        force_quick_gelu=True
    )
    tokenizer = open_clip.get_tokenizer('ViT-B-16')
    model = model.to(device)
    model.eval()

    # ==========================================
    # 5. Load Tiles DataLoader
    # ==========================================
    dataset = WSITileDataset(SLIDE_TILES_DIR, transform=preprocess)
    dataloader = DataLoader(dataset, batch_size=128, shuffle=False, num_workers=4, pin_memory=True)
    print(f"Total tiles to evaluate: {len(dataset)}")

    # Encode text features
    text = tokenizer(text_label_list).to(device)

    results = []

    with torch.no_grad(), torch.cuda.amp.autocast():
        text_features = model.encode_text(text)
        text_features /= text_features.norm(dim=-1, keepdim=True)

        for images, filenames in tqdm(dataloader, desc="Evaluating Tiles"):
            images = images.to(device)

            image_features = model.encode_image(images)
            image_features /= image_features.norm(dim=-1, keepdim=True)

            # Compute Cosine Similarity and convert to Softmax probabilities
            text_probs = (100.0 * image_features @ text_features.T).softmax(dim=-1)
            preds = torch.argmax(text_probs, dim=-1)

            # Record batch predictions
            for filename, prob, pred in zip(filenames, text_probs.cpu().numpy(), preds.cpu().numpy()):
                row = {"filename": filename, "predicted_class": class_names[pred]}
                # Store probability for each class
                for i, c in enumerate(class_names):
                    row[f"prob_{c}"] = float(prob[i])
                results.append(row)

    # ==========================================
    # 6. Save Results and Compute Slide-Level Aggregation
    # ==========================================
    df = pd.DataFrame(results)
    df.to_csv(OUTPUT_CSV, index=False)
    print(f"\nSaved tile-level predictions to: {OUTPUT_CSV}")

    # Compute slide-level average probability aggregation (Mean Pooling)
    mean_probs = {c: df[f"prob_{c}"].mean() for c in class_names}
    slide_pred = max(mean_probs, key=mean_probs.get)

    print("\n==========================================")
    print(f"Slide-Level Aggregated Probabilities:")
    for c, p in mean_probs.items():
        print(f"  - {c}: {p*100:.2f}%")
    print(f"Slide Prediction: {slide_pred}")
    print("==========================================")

    wandb.log({
        "slide_prediction": slide_pred,
        **{f"slide_mean_prob_{c}": p for c, p in mean_probs.items()}
    })
    wandb.finish()

if __name__ == "__main__":
    main()